use tomni_ui_render::kurbo::{Affine, BezPath, Point};

/// Um ícone: o caminho SVG e o lado do quadrado em que foi desenhado.
#[derive(Clone, Copy, Debug)]
pub(crate) struct Icon {
    d: &'static str,
    size: f64,
}

impl Icon {
    /// Ícone com o caminho `d`, desenhado num quadrado de `size` px.
    pub(crate) const fn new(d: &'static str, size: f64) -> Self {
        Self { d, size }
    }

    /// Lado do quadrado em que foi desenhado.
    #[cfg(test)]
    pub(crate) fn size(self) -> f64 {
        self.size
    }

    /// O caminho com o canto superior esquerdo em `origin`, num quadrado de `size` px.
    pub(crate) fn path(self, origin: Point, size: f64) -> BezPath {
        let mut path = BezPath::from_svg(self.d).expect("os caminhos embutidos são SVG válido");
        path.apply_affine(Affine::translate(origin.to_vec2()) * Affine::scale(size / self.size));
        path
    }
}

