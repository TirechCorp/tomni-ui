#[cfg(test)]
mod tests {
    use super::*;
    use tomni_ui_render::kurbo::Shape;

    #[test]
    fn caminhos_embutidos_sao_validos() {
        for icon in [
            CHECKMARK_12,
            DISMISS_16,
            INFO_16,
            CHECKMARK_CIRCLE_16,
            ERROR_CIRCLE_16,
            DISMISS_CIRCLE_16,
            CHEVRON_DOWN_12,
            CHEVRON_UP_12,
            DISMISS_12,
            EYE_12,
            CHEVRON_UP_16,
            CHEVRON_DOWN_16,
            CHEVRON_UP_DOWN_16,
        ] {
            let path = icon.path(Point::new(10.0, 20.0), icon.size * 2.0);
            let bounds = path.bounding_box();
            assert!(bounds.x0 >= 10.0 && bounds.y0 >= 20.0, "{bounds:?}");
            assert!(bounds.x1 <= 10.0 + icon.size * 2.0, "{bounds:?}");
            assert!(bounds.y1 <= 20.0 + icon.size * 2.0, "{bounds:?}");
        }
    }
}
